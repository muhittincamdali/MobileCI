import Foundation

/// Builds workflow YAML line by line with two-space indentation.
struct WorkflowWriter {
    private(set) var lines: [String] = []

    var text: String { lines.joined(separator: "\n") + "\n" }

    mutating func add(_ indent: Int, _ text: String) {
        lines.append(String(repeating: "  ", count: indent) + text)
    }

    mutating func blank() {
        if lines.last?.isEmpty == false { lines.append("") }
    }

    /// A single-quoted YAML scalar. Values are validated before they get here (no quotes,
    /// no control characters, no `${{`), so quoting only guards against YAML reading `yes`,
    /// `1.10` or `null` as something other than text.
    static func quoted(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "''") + "'"
    }

    // MARK: Shared sections

    mutating func header(kind: String, directory: String, fileName: String, options: GeneratorOptions) {
        let location = directory == "." ? "the repository root" : directory
        add(0, "# Generated by MobileCI \(MobileCIInfo.version) (\(MobileCIInfo.repositoryURL)) for the \(kind) in \(location).")
        add(0, "# Edit it like any workflow and check it with `mobileci lint`; `mobileci init --force` writes it again.")
        add(0, "name: " + (directory == "." ? kind : "\(kind) (\(directory))"))
        blank()
        add(0, "on:")
        add(1, "push:")
        add(2, "branches: [\(Self.quoted(options.branch))]")
        pathFilter(directory: directory, fileName: fileName)
        add(1, "pull_request:")
        pathFilter(directory: directory, fileName: fileName)
        add(1, "workflow_dispatch:")
        blank()
        add(0, "permissions:")
        add(1, "contents: read")
        blank()
        add(0, "# A new push to a pull request cancels its older runs; pushes to the branch run to the end.")
        add(0, "concurrency:")
        add(1, "group: ${{ github.workflow }}-${{ github.ref }}")
        add(1, "cancel-in-progress: ${{ github.event_name == 'pull_request' }}")
        blank()
        add(0, "jobs:")
    }

    /// A project in a subfolder only runs when its files or this workflow change.
    private mutating func pathFilter(directory: String, fileName: String) {
        guard directory != "." else { return }
        add(2, "paths:")
        add(3, "- " + Self.quoted(directory + "/**"))
        add(3, "- " + Self.quoted(".github/workflows/" + fileName))
    }

    mutating func job(_ id: String, name: String, runner: String, timeout: Int) {
        add(1, "\(id):")
        add(2, "name: \(name)")
        add(2, "runs-on: \(runner)")
        add(2, "timeout-minutes: \(timeout)")
    }

    mutating func developerDirectory(_ options: GeneratorOptions) {
        add(2, "env:")
        add(3, "DEVELOPER_DIR: /Applications/Xcode_\(options.xcodeVersion).app/Contents/Developer")
    }

    mutating func workingDirectory(_ directory: String) {
        guard directory != "." else { return }
        add(2, "defaults:")
        add(3, "run:")
        add(4, "working-directory: \(Self.quoted(directory))")
    }

    mutating func steps() {
        add(2, "steps:")
    }

    mutating func checkout() {
        add(3, "- uses: \(PinnedAction.checkout.reference)")
        add(4, "with:")
        add(5, "persist-credentials: false")
    }

    mutating func step(_ name: String, run command: String, workingDirectory: String? = nil, env: [(String, String)] = []) {
        blank()
        add(3, "- name: \(name)")
        if let workingDirectory { add(4, "working-directory: \(Self.quoted(workingDirectory))") }
        if !env.isEmpty {
            add(4, "env:")
            for (key, value) in env { add(5, "\(key): \(Self.quoted(value))") }
        }
        let commandLines = command.split(separator: "\n", omittingEmptySubsequences: false)
        if commandLines.count == 1 {
            add(4, "run: \(command)")
        } else {
            add(4, "run: |")
            for line in commandLines { add(5, String(line)) }
        }
    }

    mutating func uses(_ name: String, _ action: PinnedAction, with inputs: [(String, String)], condition: String? = nil) {
        blank()
        add(3, "- name: \(name)")
        if let condition { add(4, "if: \(condition)") }
        add(4, "uses: \(action.reference)")
        guard !inputs.isEmpty else { return }
        add(4, "with:")
        for (key, value) in inputs { add(5, "\(key): \(value)") }
    }
}

extension String {
    /// `folder/name`, or `name` alone for the root folder `.`.
    func joinedPath(_ name: String) -> String {
        self == "." ? name : self + "/" + name
    }
}
